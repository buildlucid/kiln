import { describe, expect, test } from "vite-plus/test";
import { createKiln, generateTypes, memoryLoader } from "../../src/index.js";
import { lines } from "../helpers.js";

/** Generates types for the given templates, listing them all. */
const generate = (templates: Record<string, string>) => {
	const loader = memoryLoader(templates);
	const kiln = createKiln({ loader, types: { Post: () => true } });
	return generateTypes(kiln, loader.list());
};

/** The entry for one template, from `"name": {` to its closing brace. */
const entry = (output: string, name: string) => {
	const start = output.indexOf(`\t\t${JSON.stringify(name)}: {`);
	return output.slice(start, output.indexOf("\n\t\t};", start) + 5);
};

describe("generateTypes", () => {
	test("writes a declaration file from each template's props", async () => {
		expect(
			await generate({
				"components/card": lines(
					'{% props post: Post, tags: string[] = [], size: "sm" | "md" = "md", link: { href: string, "aria-label"?: string } | null, extra %}',
				),
			}),
		).toBe(
			lines(
				"// Generated by Kiln's generateTypes. Do not edit.",
				'import type { KilnTypes, Markup } from "@lucidkiln/core";',
				"",
				"type Named<Name extends string> = Name extends keyof KilnTypes ? KilnTypes[Name] : unknown;",
				"",
				'declare module "@lucidkiln/core" {',
				"\tinterface KilnTemplates {",
				'\t\t"components/card": {',
				"\t\t\tcontext: {",
				'\t\t\t\tpost: Named<"Post">;',
				"\t\t\t\ttags?: readonly (string | Markup)[] | null;",
				'\t\t\t\tsize?: "sm" | "md" | null;',
				'\t\t\t\tlink: { href: string | Markup; "aria-label"?: string | Markup } | null;',
				"\t\t\t\textra: unknown;",
				"\t\t\t};",
				"\t\t\tblocks: never;",
				"\t\t};",
				"\t}",
				"}",
				"",
			),
		);
	});

	test("a rest prop allows any other key", async () => {
		const output = await generate({ link: "{% props href, ...attributes %}" });
		expect(entry(output, "link")).toContain(
			lines(
				"\t\t\tcontext: {",
				"\t\t\t\thref: unknown;",
				"\t\t\t\t[key: string]: unknown;",
				"\t\t\t};",
			),
		);
	});

	test("maps every built-in type", async () => {
		const output = await generate({
			all: "{% props a: null | boolean | number, b: array, c: hash, d: set, e: date, f: markup, g: object, h: number[], i: number[][] %}",
		});
		expect(entry(output, "all")).toContain(
			lines(
				"\t\t\t\ta: null | boolean | number;",
				"\t\t\t\tb: readonly unknown[];",
				"\t\t\t\tc: Readonly<Record<string, unknown>> | ReadonlyMap<string, unknown>;",
				"\t\t\t\td: ReadonlySet<unknown>;",
				"\t\t\t\te: Date;",
				"\t\t\t\tf: Markup;",
				"\t\t\t\tg: object;",
				"\t\t\t\th: readonly number[];",
				"\t\t\t\ti: readonly (readonly number[])[];",
			),
		);
	});

	test("a page without props takes any data, plus layout props it doesn't set", async () => {
		const output = await generate({
			"layouts/base":
				'{% props lang, title = "" %}{% block head %}{% endblock %}{% block content %}{% endblock %}',
			"layouts/docs":
				'{% extends "layouts/base" %}{% props section %}{% set lang = "en" %}{% block content %}{% endblock %}',
			"pages/guide":
				'{% extends "layouts/docs" %}{% set section = "Guides" %}{% block content %}{% endblock %}{% block aside %}{% endblock %}',
			"pages/about": '{% extends "layouts/base" %}',
		});
		expect(entry(output, "pages/guide")).toBe(
			lines(
				'\t\t"pages/guide": {',
				"\t\t\tcontext: {",
				"\t\t\t\ttitle?: unknown;",
				"\t\t\t} & Record<string, unknown>;",
				'\t\t\tblocks: "content" | "aside" | "head";',
				"\t\t};",
			),
		);
		expect(entry(output, "pages/about")).toContain(
			lines(
				"\t\t\t\tlang: unknown;",
				"\t\t\t\ttitle?: unknown;",
				"\t\t\t} & Record<string, unknown>;",
			),
		);
	});

	test("a page with props takes exactly its props", async () => {
		const output = await generate({
			base: "{% props lang %}",
			page: '{% extends "base" %}{% props title %}',
		});
		expect(entry(output, "page")).toContain(
			lines("\t\t\tcontext: {", "\t\t\t\ttitle: unknown;", "\t\t\t};"),
		);
	});

	test("takes any data and block when a layout can't be found", async () => {
		const output = await generate({
			computed: "{% extends layout %}{% block a %}{% endblock %}",
			missing: '{% extends "nope" %}',
		});
		for (const name of ["computed", "missing"]) {
			expect(entry(output, name)).toContain(
				lines(
					"\t\t\tcontext: Record<string, unknown>;",
					"\t\t\tblocks: string;",
				),
			);
		}
	});

	test("sorts templates, drops .kiln from names and skips missing ones", async () => {
		const loader = memoryLoader({ b: "", "a.txt": "" });
		const output = await generateTypes(createKiln({ loader }), [
			"b.kiln",
			"a.txt",
			"b",
			"gone",
		]);
		expect(output).toBe(
			lines(
				"// Generated by Kiln's generateTypes. Do not edit.",
				"export {};",
				"",
				'declare module "@lucidkiln/core" {',
				"\tinterface KilnTemplates {",
				'\t\t"a.txt": {',
				"\t\t\tcontext: Record<string, unknown>;",
				"\t\t\tblocks: never;",
				"\t\t};",
				'\t\t"b": {',
				"\t\t\tcontext: Record<string, unknown>;",
				"\t\t\tblocks: never;",
				"\t\t};",
				"\t}",
				"}",
				"",
			),
		);
	});

	test("writes an empty interface when there are no templates", async () => {
		expect(await generate({})).toContain("\tinterface KilnTemplates {}");
	});
});
