/**
 * The keywords an attribute accepts. `on` lists the elements it applies to, or is `*` for any element. `tokens` takes a
 * list of keywords separated by spaces. `other` accepts values that aren't keywords, such as `target` names.
 */
export type AttributeValues = {
	on: readonly string[] | "*";
	values: readonly string[];
	caseSensitive?: true;
	tokens?: true;
	other?: (value: string) => boolean;
};

